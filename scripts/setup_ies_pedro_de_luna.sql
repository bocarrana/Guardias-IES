-- 4. Crear Políticas RLS
DO $$ 
DECLARE
    tbl text;
BEGIN
    FOR tbl IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' 
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Permitir lectura para todos" ON public.%I', tbl);
        EXECUTE format('CREATE POLICY "Permitir lectura para todos" ON public.%I FOR SELECT USING (true)', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "Permitir escritura para todos" ON public.%I', tbl);
        EXECUTE format('CREATE POLICY "Permitir escritura para todos" ON public.%I FOR ALL USING (true)', tbl);
    END LOOP;
END $$;

