CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

BEGIN;

-- 1. Tipo de Datos de Usuarios
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'Tipos de usuarios') THEN
        CREATE TYPE "Tipos de usuarios" AS ENUM ('superadmin', 'Administrador', 'Admin', 'Jefatura', 'Administración', 'Docente', 'Usuario', 'Pantalla');
    END IF;
END $$;

-- 2. Creación de Tablas Principales

CREATE TABLE IF NOT EXISTS public."Profesores" (
    id text PRIMARY KEY,
    "nombre y apellidos" text NOT NULL,
    email text UNIQUE,
    departamento text,
    "grupo de guardia" text,
    foto text,
    avatar_seed text,
    rol text DEFAULT 'Usuario',
    user_id uuid,
    horas_guardia integer DEFAULT 1,
    activo boolean DEFAULT true
);

CREATE TABLE IF NOT EXISTS public."Franjas horarias" (
    "id franja" text PRIMARY KEY,
    franja text,
    "hora inicio" text,
    "hora fin" text,
    tipo text
);

CREATE TABLE IF NOT EXISTS public."Aulas" (
    "id aulas" text PRIMARY KEY,
    aulas text UNIQUE NOT NULL,
    edificio text,
    ubicacion text
);

CREATE TABLE IF NOT EXISTS public."Materias" (
    "id materias" text PRIMARY KEY,
    materias text UNIQUE NOT NULL,
    padre_id text
);

CREATE TABLE IF NOT EXISTS public."Grupos" (
    "id grupos" text PRIMARY KEY,
    grupos text UNIQUE NOT NULL,
    tutor_id text REFERENCES public."Profesores"(id) ON DELETE SET NULL,
    nivel text,
    aula_habitual text
);

CREATE TABLE IF NOT EXISTS public."Grupos_Guardia" (
    id text PRIMARY KEY,
    nombre text NOT NULL,
    profesores_asignados jsonb DEFAULT '[]'::jsonb,
    color text,
    "orden_rotación" integer,
    activo boolean DEFAULT true
);

CREATE TABLE IF NOT EXISTS public."Horario_Personal" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesor_id text REFERENCES public."Profesores"(id) ON DELETE CASCADE,
    "día" integer NOT NULL,
    tramo_horario text REFERENCES public."Franjas horarias"("id franja") ON DELETE CASCADE,
    asignatura text,
    grupo text,
    aula text,
    es_guardia boolean DEFAULT false,
    tipo_guardia text,
    created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."Guardias" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "profesor que falta" text REFERENCES public."Profesores"(id) ON DELETE SET NULL,
    fecha date NOT NULL,
    horario text REFERENCES public."Franjas horarias"("id franja") ON DELETE RESTRICT,
    "aula de guardia" text,
    "grupo de alumnos" text,
    "profesor de guardia" text REFERENCES public."Profesores"(id) ON DELETE SET NULL,
    "tipo de guardia" text,
    estado text DEFAULT 'Pendiente',
    motivo text,
    observaciones text,
    tarea text,
    firma_confirmacion text,
    "hora de firma" timestamp with time zone,
    created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."Activity_Logs" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid,
    user_email text,
    user_name text,
    action text NOT NULL,
    entity_type text,
    entity_id text,
    details jsonb,
    ip_address text,
    created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."reservas_aulas" (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    aula_id text REFERENCES public."Aulas"("id aulas") ON DELETE CASCADE,
    profesor_id text REFERENCES public."Profesores"(id) ON DELETE CASCADE,
    fecha date NOT NULL,
    tramo_horario text REFERENCES public."Franjas horarias"("id franja") ON DELETE CASCADE,
    motivo text,
    anual boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."libre_disposicion" (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    profesor_id text REFERENCES public."Profesores"(id) ON DELETE CASCADE,
    fecha date NOT NULL,
    motivo text,
    created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."configuracion_centro" (
    id integer PRIMARY KEY,
    nombre_centro text,
    direccion_centro text,
    telefono_centro text,
    email_centro text,
    logo_url text
);

-- Tabla: Calendario
CREATE TABLE IF NOT EXISTS public."Calendario" (
    "id" BIGSERIAL PRIMARY KEY,
    "fecha" DATE UNIQUE NOT NULL,
    "es_lectivo" BOOLEAN NOT NULL DEFAULT true,
    "descripcion" TEXT,
    "created_at" TIMESTAMPTZ DEFAULT NOW()
);

-- Tabla: calendar_events
CREATE TABLE IF NOT EXISTS public.calendar_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    date DATE NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

